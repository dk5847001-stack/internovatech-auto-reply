async function sendMail({

to,

subject,

text,

inReplyTo=null

}){



let attempts=0;


const maxAttempts=3;



while(attempts < maxAttempts){



try{



attempts++;




let cleanContent =
cleanSignature(text);




if(!cleanContent){


cleanContent =
"Hello,\n\nThank you for contacting InternovaTech. We have received your message.";

}





const html =
createTemplate(`

<p>
Hello,
</p>


<p>
${escapeHtml(cleanContent).replace(/\n/g,"<br>")}
</p>



<br>


<p>
Regards,<br>

<b>
InternovaTech Support Team
</b>

</p>

`);







const mailOptions={


from:{


name:"InternovaTech Support",

address:process.env.EMAIL


},



to,


subject,



text:
stripHtml(cleanContent),



html,



headers:{}

};







if(inReplyTo){


mailOptions.headers["In-Reply-To"]
=
inReplyTo;


mailOptions.headers["References"]
=
inReplyTo;


}






const info =
await transporter.sendMail(
mailOptions
);



console.log(
"📤 Email Sent:",
info.messageId
);



return info;




}

catch(error){



console.error(
`SMTP Attempt ${attempts} Failed:`,
error.message
);



if(attempts >= maxAttempts){

throw error;

}



await new Promise(

resolve=>setTimeout(resolve,5000)

);


}



}



}






