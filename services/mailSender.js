async function sendMail({

to,

subject,

text,

inReplyTo=null


}){


try{


let cleanContent =
removeDuplicateSignature(text);


if(!cleanContent){


cleanContent =
"Hello,\n\nThank you for contacting InternovaTech. We have received your message and will assist you shortly.";


}







let html;


if(
cleanContent.includes("<p") ||
cleanContent.includes("<h2") ||
cleanContent.includes("<div") ||
cleanContent.includes("<ul") ||
cleanContent.includes("<ol")
){

html =
createTemplate(cleanContent);


}
else{


html =
createTemplate(
`
<p>
Hello,
</p>

<p>
${escapeHtml(cleanContent).replace(/\n/g,"<br>")}
</p>
`
);


}







const mailOptions={


from:{

name:"InternovaTech Support",

address:process.env.EMAIL

},



to,


subject,



text:
stripHtml(cleanContent),



html,



headers:{}


};






if(inReplyTo){


mailOptions.headers["In-Reply-To"]
=
inReplyTo;


mailOptions.headers["References"]
=
inReplyTo;


}







const info =
await transporter.sendMail(
mailOptions
);



console.log(
"📤 Email Sent:",
info.messageId
);



return info;



}

catch(error){


console.error(
"❌ Mail Send Error:",
error
);


throw error;


}


}





