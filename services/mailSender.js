async function sendMail({

to,

subject,

text,

inReplyTo=null


}){


try{


const message =
text || 
"Thank you for contacting InternovaTech.";



const html =
createTemplate(`

<p>Hello,</p>


<p>

${escapeHtml(message).replace(/\n/g,"<br>")}

</p>


`);






const email = 
new brevo.SendSmtpEmail();



email.sender = {

name:
"InternovaTech Support",

email:
process.env.FROM_EMAIL

};



email.to = [

{

email:to

}

];



email.subject =
subject;



email.textContent =
message;



email.htmlContent =
html;





if(inReplyTo){


email.headers = {


"In-Reply-To":
inReplyTo,


"References":
inReplyTo


};


}






const result =
await apiInstance.sendTransacEmail(email);



console.log(
"📤 Brevo Email Sent:",
result.messageId || "Success"
);



return result;



}

catch(error){


console.error(

"❌ Brevo API Error:",

error.response?.body ||
error.message

);


throw error;


}


}




