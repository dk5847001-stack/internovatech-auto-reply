function textValue(value){


if(!value)
return "";


if(typeof value==="object"){

return String(
value.message ||
value.text ||
value.body ||
""
);

}


return String(value);


}








function escapeHtml(value){


return textValue(value)

.replace(/&/g,"&amp;")

.replace(/</g,"&lt;")

.replace(/>/g,"&gt;")

.replace(/"/g,"&quot;")

.replace(/'/g,"&#039;");


}









function stripHtml(value){


return textValue(value)

.replace(/<style[\s\S]*?<\/style>/gi,"")

.replace(/<script[\s\S]*?<\/script>/gi,"")

.replace(/<br\s*\/?>/gi,"\n")

.replace(/<\/p>/gi,"\n")

.replace(/<[^>]*>/g,"")

.replace(/&nbsp;/gi," ")

.trim();


}









function cleanSignature(text){


return textValue(text)

.replace(
/Regards,[\s\S]*?(InternovaTech Support Team|InternovaTech Team|InternovaTech Support)/gi,
""
)

.trim();


}









