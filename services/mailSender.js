function toMessageText(value){

if(value === null || value === undefined){
return "";
}

if(typeof value === "object"){
return String(value.message || value.text || value.body || "");
}

return String(value);

}


function escapeHtml(value){

return toMessageText(value)
.replace(/&/g,"&amp;")
.replace(/</g,"&lt;")
.replace(/>/g,"&gt;")
.replace(/"/g,"&quot;")
.replace(/'/g,"&#039;");

}


function stripHtml(value){

return toMessageText(value)
.replace(/<style[\s\S]*?<\/style>/gi,"")
.replace(/<script[\s\S]*?<\/script>/gi,"")
.replace(/<br\s*\/?>/gi,"\n")
.replace(/<\/p>/gi,"\n\n")
.replace(/<\/li>/gi,"\n")
.replace(/<[^>]*>/g,"")
.replace(/&nbsp;/gi," ")
.replace(/&amp;/gi,"&")
.replace(/&lt;/gi,"<")
.replace(/&gt;/gi,">")
.replace(/&quot;/gi,"\"")
.replace(/&#039;/gi,"'")
.replace(/\n{3,}/g,"\n\n")
.trim();

}


function removeDuplicateSignature(value){

return toMessageText(value)
.replace(/Regards,[\s\S]*?(InternovaTech Support Team|InternovaTech Team)/gi,"")
.trim();

}


